//! Deterministic AVR C code generation from the typed IR.
//!
//! Output is a pure function of (device definition, project configuration,
//! IR, options): no timestamps or host-specific data are embedded. Generated
//! files are ASCII-only for compatibility with WinAVR-era compilers.

use crate::config_validation::compute_baud;
use crate::device_registry::{DeviceDefinition, RegisterProfile};
use crate::graph::ir::*;
use crate::paths::atomic_write;
use crate::project_store::{Parity, PinMode, Project, VarType};
use crate::{CoreError, CoreResult};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

pub const GENERATED_DIR: &str = "src/generated";
pub const GENERATED_MARKER: &str = "AUTO-GENERATED by AVR Studio Visual";
const MANIFEST_NAME: &str = ".avsv-generated.json";

#[derive(Debug, Clone, Copy, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CodegenOptions {
    /// WinAVR-era avr-libc: `_delay_ms`/`_delay_us` have small maximum
    /// arguments, so long delays are emitted as loops of short delays.
    pub legacy_toolchain: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedFile {
    /// Path relative to the project root, using forward slashes.
    pub path: String,
    pub content: String,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedCode {
    pub files: Vec<GeneratedFile>,
    pub f_cpu: u32,
}

pub fn generate(
    device: &DeviceDefinition,
    project: &Project,
    ir: &IrProgram,
    opts: CodegenOptions,
) -> GeneratedCode {
    let g = Gen {
        device,
        project,
        ir,
        opts,
        profile: device.register_profile,
    };
    let files = vec![
        GeneratedFile {
            path: format!("{GENERATED_DIR}/avsv_config.h"),
            content: g.config_h(),
        },
        GeneratedFile {
            path: format!("{GENERATED_DIR}/avsv_hal.h"),
            content: g.hal_h(),
        },
        GeneratedFile {
            path: format!("{GENERATED_DIR}/avsv_hal.c"),
            content: g.hal_c(),
        },
        GeneratedFile {
            path: format!("{GENERATED_DIR}/main.c"),
            content: g.main_c(),
        },
    ];
    GeneratedCode {
        files,
        f_cpu: project.clock.f_cpu(),
    }
}

struct Gen<'a> {
    device: &'a DeviceDefinition,
    project: &'a Project,
    ir: &'a IrProgram,
    opts: CodegenOptions,
    profile: RegisterProfile,
}

fn ascii(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii() && !c.is_ascii_control() {
                c
            } else {
                '?'
            }
        })
        .collect()
}

/// Escapes text as a C string literal body. Non-printable bytes, quotes,
/// backslashes and '?' (trigraphs) are written as 3-digit octal escapes.
pub fn c_string(s: &str) -> String {
    let mut out = String::new();
    for b in s.bytes() {
        if (0x20..0x7f).contains(&b) && b != b'"' && b != b'\\' && b != b'?' {
            out.push(b as char);
        } else {
            let _ = write!(out, "\\{b:03o}");
        }
    }
    out
}

fn int_literal(v: i64) -> String {
    let lit = if (i16::MIN as i64..=i16::MAX as i64).contains(&v) {
        v.to_string()
    } else if (i32::MIN as i64..=i32::MAX as i64).contains(&v) {
        format!("{v}L")
    } else {
        format!("{v}UL")
    };
    if v < 0 { format!("({lit})") } else { lit }
}

