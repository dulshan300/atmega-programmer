impl Gen<'_> {
    fn usart(&self) -> &'static Usart {
        match self.profile {
            RegisterProfile::MegaX8 => &USART_X8,
            RegisterProfile::MegaLegacy => &USART_LEGACY,
        }
    }

    fn banner(&self, what: &str) -> String {
        let m = &self.project.manifest;
        format!(
            "/*\n * {GENERATED_MARKER} -- DO NOT EDIT.\n *\n * {what}\n * Project : {}\n * Device  : {} ({})\n * F_CPU   : {} Hz\n *\n * This file is regenerated from visual/main.flow.json and config/*.json.\n * Manual changes are detected and the application will refuse to overwrite them.\n */\n\n",
            ascii(&m.name),
            self.device.name,
            m.device.package,
            self.project.clock.f_cpu()
        )
    }

    fn uart_on(&self) -> bool {
        self.project.peripherals.usart.enabled
    }
    fn adc_on(&self) -> bool {
        self.project.peripherals.adc.enabled
    }
    fn jtag_off(&self) -> bool {
        self.project.peripherals.disable_jtag_at_startup && self.device.jtag_pins.is_some()
    }

    fn config_h(&self) -> String {
        let mut s = self.banner("Build configuration and pin mapping.");
        let macro_name = format!("__AVR_{}__", self.device.name);
        let f_cpu = self.project.clock.f_cpu();
        let _ = write!(
            s,
            "#ifndef AVSV_CONFIG_H\n#define AVSV_CONFIG_H\n\n#if !defined({macro_name})\n#error \"This firmware was generated for the {name}. Check the -mmcu compiler option.\"\n#endif\n\n/* CPU clock assumed by delays and baud-rate calculations.\n * Clock source: {src}, {hz} Hz{div}.\n * The chip only runs at this speed if its fuses select the same clock source. */\n#ifndef F_CPU\n#define F_CPU {f_cpu}UL\n#endif\n#if F_CPU != {f_cpu}UL\n#error \"F_CPU does not match the project clock configuration ({f_cpu} Hz).\"\n#endif\n\n",
            name = self.device.name,
            src = self.project.clock.source,
            hz = self.project.clock.source_frequency_hz,
            div = if self.project.clock.ckdiv8 {
                ", divided by 8 (CKDIV8)"
            } else {
                ""
            },
        );
        let mut pins: Vec<_> = self.project.pins.assignments.iter().collect();
        pins.sort_by(|a, b| a.pin.cmp(&b.pin));
        if !pins.is_empty() {
            s.push_str("/* Pin mapping */\n");
        }
        for a in pins {
            let Some(p) = self.device.pin(&a.pin) else {
                continue;
            };
            let phys = self
                .device
                .physical_pin(&self.project.manifest.device.package, &a.pin)
                .map(|n| format!("physical pin {n}"))
                .unwrap_or_else(|| "not bonded".into());
            let _ = write!(
                s,
                "/* {label}: {pin} ({phys}), {mode} */\n#define IO_{label}_PORT PORT{port}\n#define IO_{label}_DDR  DDR{port}\n#define IO_{label}_PIN  PIN{port}\n#define IO_{label}_BIT  {bit}\n\n",
                label = a.label,
                pin = a.pin,
                mode = crate::config_validation::pin_mode_label(a.mode),
                port = p.port,
                bit = p.bit
            );
        }
        s.push_str("#endif /* AVSV_CONFIG_H */\n");
        s
    }

    fn hal_h(&self) -> String {
        let mut s = self.banner("Hardware abstraction helpers.");
        s.push_str("#ifndef AVSV_HAL_H\n#define AVSV_HAL_H\n\n#include <stdint.h>\n#include <stdbool.h>\n\n");
        s.push_str("/* Configures pins, peripherals and interrupts from the project configuration. */\nvoid avsv_init(void);\n");
        if self.ir.uses.variable_delay || self.opts.legacy_toolchain {
            s.push_str("void avsv_delay_ms(uint16_t ms);\n");
        }
        if self.uart_on() {
            s.push_str(
                "\n/* USART */\nvoid avsv_uart_putc(uint8_t c);\nuint8_t avsv_uart_getc(void);\nbool avsv_uart_available(void);\nvoid avsv_uart_puts_P(const char *s);\nvoid avsv_uart_print_i32(int32_t value);\n",
            );
        }
        if self.adc_on() {
            s.push_str("\n/* ADC */\nuint16_t avsv_adc_read(uint8_t channel);\n");
        }
        s.push_str("\n#endif /* AVSV_HAL_H */\n");
        s
    }

    fn hal_c(&self) -> String {
        let mut s = self.banner("Peripheral initialization and helper functions.");
        s.push_str("#include \"avsv_config.h\"\n\n#include <avr/io.h>\n");
        if self.uart_on() {
            s.push_str("#include <avr/pgmspace.h>\n");
        }
        if !self.ir.external_interrupts.is_empty() {
            s.push_str("#include <avr/interrupt.h>\n");
        }
        s.push_str("#include <util/delay.h>\n\n#include \"avsv_hal.h\"\n\n");

        if self.uart_on() {
            s.push_str(&self.uart_impl());
        }
        if self.adc_on() {
            s.push_str(&self.adc_impl());
        }
        if self.ir.uses.variable_delay || self.opts.legacy_toolchain {
            s.push_str("void avsv_delay_ms(uint16_t ms)\n{\n    while (ms-- > 0U) {\n        _delay_ms(1);\n    }\n}\n\n");
        }

        s.push_str("void avsv_init(void)\n{\n");
        if self.jtag_off() {
            s.push_str(
                "    /* Disable the JTAG interface so its pins can be used as GPIO.\n     * JTD must be written twice within four clock cycles. */\n    __asm__ __volatile__(\n        \"out %0, %1\\n\\t\"\n        \"out %0, %1\\n\\t\"\n        :\n        : \"I\"(_SFR_IO_ADDR(MCUCSR)), \"r\"((uint8_t)(MCUCSR | (1U << JTD))));\n\n",
            );
        }
        s.push_str(&self.gpio_init());
        if self.uart_on() {
            s.push_str("    avsv_uart_init();\n");
        }
        if self.adc_on() {
            s.push_str("    avsv_adc_init();\n");
        }
        for isr in &self.ir.external_interrupts {
            s.push_str(&self.ext_int_init(isr));
        }
        if !self.ir.external_interrupts.is_empty() {
            s.push_str("\n    /* Enable global interrupts */\n    sei();\n");
        }
        s.push_str("}\n");
        s
    }

    fn gpio_init(&self) -> String {
        let mut pins: Vec<_> = self.project.pins.assignments.iter().collect();
        pins.sort_by(|a, b| a.pin.cmp(&b.pin));
        if pins.is_empty() {
            return "    /* No GPIO pins configured. */\n".into();
        }
        let mut s = String::from("    /* GPIO */\n");
        for a in pins {
            let l = &a.label;
            let bit = format!("(uint8_t)(1U << IO_{l}_BIT)");
            let nbit = format!("(uint8_t)~(1U << IO_{l}_BIT)");
            match a.mode {
                PinMode::Output => {
                    let level = if a.initial_high {
                        format!("IO_{l}_PORT |= {bit};")
                    } else {
                        format!("IO_{l}_PORT &= {nbit};")
                    };
                    let _ = writeln!(
                        s,
                        "    {level} /* {pin} {l}: initially {} */\n    IO_{l}_DDR |= {bit};",
                        if a.initial_high { "high" } else { "low" },
                        pin = a.pin
                    );
                }
                PinMode::Input => {
                    let _ = writeln!(
                        s,
                        "    IO_{l}_DDR &= {nbit}; /* {} {l}: input */\n    IO_{l}_PORT &= {nbit};",
                        a.pin
                    );
                }
                PinMode::InputPullup => {
                    let _ = writeln!(
                        s,
                        "    IO_{l}_DDR &= {nbit}; /* {} {l}: input, pull-up */\n    IO_{l}_PORT |= {bit};",
                        a.pin
                    );
                }
            }
        }
        s
    }

    fn uart_impl(&self) -> String {
        let u = self.usart();
        let cfg = &self.project.peripherals.usart;
        let f_cpu = self.project.clock.f_cpu();
        // Validation rejects unreachable baud rates before code generation.
        let b = compute_baud(f_cpu, cfg.baud).unwrap_or(crate::config_validation::BaudSetting {
            ubrr: 0,
            double_speed: false,
            actual_baud: 0.0,
            error_percent: 0.0,
        });
        let mut frame = vec![];
        if let Some(ursel) = u.ursel {
            frame.push(format!("(1U << {ursel})"));
        }
        match cfg.data_bits {
            6 => frame.push(format!("(1U << {})", u.ucsz0)),
            7 => frame.push(format!("(1U << {})", u.ucsz1)),
            8 => frame.push(format!("(1U << {}) | (1U << {})", u.ucsz1, u.ucsz0)),
            _ => {}
        }
        match cfg.parity {
            Parity::Even => frame.push(format!("(1U << {})", u.upm1)),
            Parity::Odd => frame.push(format!("(1U << {}) | (1U << {})", u.upm1, u.upm0)),
            Parity::None => {}
        }
        if cfg.stop_bits == 2 {
            frame.push(format!("(1U << {})", u.usbs));
        }
        let frame = if frame.is_empty() {
            "0U".to_string()
        } else {
            frame.join(" | ")
        };
        let parity = match cfg.parity {
            Parity::None => 'N',
            Parity::Even => 'E',
            Parity::Odd => 'O',
        };
        let mut s = String::new();
        let _ = write!(
            s,
            "static void avsv_uart_init(void)\n{{\n    /* {baud} baud {db}{parity}{sb} from F_CPU {f_cpu} Hz:\n     * UBRR = {ubrr}, {speed} speed, actual {actual:.0} baud, error {err:+.2} % */\n    {ubrrh} = (uint8_t)({ubrr}U >> 8);\n    {ubrrl} = (uint8_t)({ubrr}U & 0xFFU);\n    {ucsra} = {u2x};\n    {ucsrc} = (uint8_t)({frame});\n    {ucsrb} = (uint8_t)((1U << {rxen}) | (1U << {txen}));\n}}\n\n",
            baud = cfg.baud,
            db = cfg.data_bits,
            sb = cfg.stop_bits,
            ubrr = b.ubrr,
            speed = if b.double_speed { "double" } else { "normal" },
            actual = b.actual_baud,
            err = b.error_percent,
            ubrrh = u.ubrrh,
            ubrrl = u.ubrrl,
            ucsra = u.ucsra,
            u2x = if b.double_speed {
                format!("(uint8_t)(1U << {})", u.u2x)
            } else {
                "0U".into()
            },
            ucsrc = u.ucsrc,
            ucsrb = u.ucsrb,
            rxen = u.rxen,
            txen = u.txen,
        );
        let _ = write!(
            s,
            "void avsv_uart_putc(uint8_t c)\n{{\n    while (({ucsra} & (1U << {udre})) == 0U) {{\n    }}\n    {udr} = c;\n}}\n\nbool avsv_uart_available(void)\n{{\n    return ({ucsra} & (1U << {rxc})) != 0U;\n}}\n\nuint8_t avsv_uart_getc(void)\n{{\n    while (({ucsra} & (1U << {rxc})) == 0U) {{\n    }}\n    return {udr};\n}}\n\nvoid avsv_uart_puts_P(const char *s)\n{{\n    char c;\n    while ((c = (char)pgm_read_byte(s++)) != '\\0') {{\n        avsv_uart_putc((uint8_t)c);\n    }}\n}}\n\nvoid avsv_uart_print_i32(int32_t value)\n{{\n    char buf[10];\n    uint8_t i = 0;\n    uint32_t v;\n    if (value < 0) {{\n        avsv_uart_putc('-');\n        v = (uint32_t)(-(value + 1)) + 1U;\n    }} else {{\n        v = (uint32_t)value;\n    }}\n    do {{\n        buf[i++] = (char)('0' + (char)(v % 10U));\n        v /= 10U;\n    }} while (v != 0U);\n    while (i > 0U) {{\n        avsv_uart_putc((uint8_t)buf[--i]);\n    }}\n}}\n\n",
            ucsra = u.ucsra,
            udre = u.udre,
            udr = u.udr,
            rxc = u.rxc,
        );
        s
    }

    fn adc_impl(&self) -> String {
        let cfg = &self.project.peripherals.adc;
        let refs = self
            .device
            .peripherals
            .adc
            .references
            .iter()
            .find(|r| r.id == cfg.reference)
            .map(|r| (r.refs_bits, r.label.clone()))
            .unwrap_or((1, "AVCC".into()));
        let mut refs_expr = vec![];
        if refs.0 & 1 != 0 {
            refs_expr.push("(1U << REFS0)");
        }
        if refs.0 & 2 != 0 {
            refs_expr.push("(1U << REFS1)");
        }
        let refs_expr = if refs_expr.is_empty() {
            "0U".to_string()
        } else {
            refs_expr.join(" | ")
        };
        let adps = cfg.prescaler.max(2).trailing_zeros();
        let mut adps_expr = vec!["(1U << ADEN)".to_string()];
        for (bit, name) in [(4, "ADPS2"), (2, "ADPS1"), (1, "ADPS0")] {
            if adps & bit != 0 {
                adps_expr.push(format!("(1U << {name})"));
            }
        }
        format!(
            "static void avsv_adc_init(void)\n{{\n    /* Reference: {label}; prescaler {pre} -> ADC clock {clk} Hz */\n    ADMUX = (uint8_t)({refs_expr});\n    ADCSRA = (uint8_t)({adcsra});\n}}\n\nuint16_t avsv_adc_read(uint8_t channel)\n{{\n    ADMUX = (uint8_t)((ADMUX & 0xE0U) | (channel & 0x07U));\n    ADCSRA |= (uint8_t)(1U << ADSC);\n    while ((ADCSRA & (1U << ADSC)) != 0U) {{\n    }}\n    return ADCW;\n}}\n\n",
            label = ascii(&refs.1),
            pre = cfg.prescaler,
            clk = self.project.clock.f_cpu() / cfg.prescaler.max(1),
            adcsra = adps_expr.join(" | "),
        )
    }

    fn ext_int_init(&self, isr: &IrExternalInterrupt) -> String {
        let code = isr.trigger.isc_bits();
        let n = isr.source.trim_start_matches("INT");
        let trig = format!("{:?}", isr.trigger).to_lowercase();
        match (self.profile, isr.source.as_str()) {
            (RegisterProfile::MegaLegacy, "INT2") => format!(
                "\n    /* INT2 on {trig} edge (ISC2 may only change while INT2 is disabled) */\n    GICR &= (uint8_t)~(1U << INT2);\n    MCUCSR {op};\n    GIFR = (uint8_t)(1U << INTF2);\n    GICR |= (uint8_t)(1U << INT2);\n",
                op = if isr.trigger == ExtTrigger::Rising {
                    "|= (uint8_t)(1U << ISC2)"
                } else {
                    "&= (uint8_t)~(1U << ISC2)"
                }
            ),
            (profile, _) => {
                let (ctrl, mask) = match profile {
                    RegisterProfile::MegaX8 => ("EICRA", "EIMSK"),
                    RegisterProfile::MegaLegacy => ("MCUCR", "GICR"),
                };
                format!(
                    "\n    /* {src} on {trig} */\n    {ctrl} = (uint8_t)(({ctrl} & (uint8_t)~((1U << ISC{n}1) | (1U << ISC{n}0))) | ({code}U << ISC{n}0));\n    {mask} |= (uint8_t)(1U << {src});\n",
                    src = isr.source
                )
            }
        }
    }

    fn main_c(&self) -> String {
        let mut s = self.banner("Program logic generated from the visual editor.");
        s.push_str("#include \"avsv_config.h\"\n\n#include <avr/io.h>\n");
        if !self.ir.external_interrupts.is_empty() {
            s.push_str("#include <avr/interrupt.h>\n");
        }
        if self.uart_on() {
            s.push_str("#include <avr/pgmspace.h>\n");
        }
        s.push_str("#include <util/delay.h>\n#include <stdint.h>\n#include <stdbool.h>\n\n#include \"avsv_hal.h\"\n\n");

        let isr_present = !self.ir.external_interrupts.is_empty();
        if !self.ir.variables.is_empty() {
            s.push_str("/* Variables */\n");
            for v in &self.ir.variables {
                let init = if v.var_type == VarType::Bool {
                    (if v.initial != 0 { "true" } else { "false" }).to_string()
                } else {
                    int_literal(v.initial)
                };
                let _ = writeln!(
                    s,
                    "static {}{} v_{} = {};",
                    if isr_present { "volatile " } else { "" },
                    v.var_type.c_type(),
                    v.name,
                    init
                );
            }
            s.push('\n');
        }
        let mut functions: Vec<_> = self.ir.functions.iter().collect();
        functions.sort_by(|a, b| a.name.cmp(&b.name));
        if !functions.is_empty() {
            s.push_str("/* Function prototypes */\n");
            for f in &functions {
                let _ = writeln!(s, "void fn_{}(void);", f.name);
            }
            s.push('\n');
        }
        let mut counter = 0usize;
        for f in &functions {
            let _ = writeln!(
                s,
                "/* Function '{}' [node {}] */\nvoid fn_{}(void)\n{{",
                f.name,
                ascii(&f.node_id),
                f.name
            );
            self.block(&mut s, &f.body, 1, &mut counter);
            s.push_str("}\n\n");
        }
        let mut isrs: Vec<_> = self.ir.external_interrupts.iter().collect();
        isrs.sort_by(|a, b| a.vector.cmp(&b.vector));
        for isr in isrs {
            let _ = writeln!(
                s,
                "/* External interrupt {} [node {}] */\nISR({})\n{{",
                isr.source,
                ascii(&isr.node_id),
                isr.vector
            );
            self.block(&mut s, &isr.body, 1, &mut counter);
            s.push_str("}\n\n");
        }
        s.push_str("/* Runs once after reset */\nstatic void avsv_setup(void)\n{\n");
        self.block(&mut s, &self.ir.setup, 1, &mut counter);
        s.push_str("}\n\n/* Runs repeatedly after setup */\nstatic void avsv_loop(void)\n{\n");
        self.block(&mut s, &self.ir.loop_body, 1, &mut counter);
        s.push_str("}\n\nint main(void)\n{\n    avsv_init();\n    avsv_setup();\n    for (;;) {\n        avsv_loop();\n    }\n    return 0;\n}\n");
        s
    }

    fn block(&self, s: &mut String, stmts: &[Stmt], depth: usize, counter: &mut usize) {
        if stmts.is_empty() {
            let _ = writeln!(s, "{}/* (empty) */", "    ".repeat(depth));
        }
        for st in stmts {
            self.stmt(s, st, depth, counter);
        }
    }

    fn bit(&self, p: &PinRef) -> String {
        format!("(uint8_t)(1U << IO_{}_BIT)", p.label)
    }

    fn stmt(&self, s: &mut String, st: &Stmt, depth: usize, counter: &mut usize) {
        let ind = "    ".repeat(depth);
        let _ = writeln!(s, "{ind}/* {} [{}] */", ascii(&st.label), ascii(&st.node_id));
        let set = |p: &PinRef| format!("IO_{}_PORT |= {};", p.label, self.bit(p));
        let clear = |p: &PinRef| format!("IO_{}_PORT &= (uint8_t)~(1U << IO_{}_BIT);", p.label, p.label);
        match &st.kind {
            StmtKind::PinMode { pin, mode } => {
                let l = &pin.label;
                match mode {
                    PinMode::Output => {
                        let _ = writeln!(s, "{ind}IO_{l}_DDR |= {};", self.bit(pin));
                    }
                    PinMode::Input => {
                        let _ = writeln!(
                            s,
                            "{ind}IO_{l}_DDR &= (uint8_t)~(1U << IO_{l}_BIT);\n{ind}{}",
                            clear(pin)
                        );
                    }
                    PinMode::InputPullup => {
                        let _ = writeln!(
                            s,
                            "{ind}IO_{l}_DDR &= (uint8_t)~(1U << IO_{l}_BIT);\n{ind}{}",
                            set(pin)
                        );
                    }
                }
            }
            StmtKind::PinWrite { pin, value } => match value {
                Expr::Bool { value: true } => {
                    let _ = writeln!(s, "{ind}{}", set(pin));
                }
                Expr::Bool { value: false } => {
                    let _ = writeln!(s, "{ind}{}", clear(pin));
                }
                e => {
                    let _ = writeln!(
                        s,
                        "{ind}if ({}) {{\n{ind}    {}\n{ind}}} else {{\n{ind}    {}\n{ind}}}",
                        self.expr(e),
                        set(pin),
                        clear(pin)
                    );
                }
            },
            StmtKind::PinToggle { pin } => {
                let line = match self.profile {
                    // Writing 1 to PINx toggles PORTx atomically on this family.
                    RegisterProfile::MegaX8 => format!("IO_{}_PIN = {};", pin.label, self.bit(pin)),
                    RegisterProfile::MegaLegacy => format!("IO_{}_PORT ^= {};", pin.label, self.bit(pin)),
                };
                let _ = writeln!(s, "{ind}{line}");
            }
            StmtKind::WaitPin { pin, level } => {
                let read = format!("(IO_{}_PIN & (1U << IO_{}_BIT))", pin.label, pin.label);
                let cond = if *level {
                    format!("{read} == 0U")
                } else {
                    format!("{read} != 0U")
                };
                let _ = writeln!(s, "{ind}while ({cond}) {{\n{ind}}}");
            }
            StmtKind::DelayMs { ms } => match ms {
                Expr::Int { value } if !self.opts.legacy_toolchain => {
                    let _ = writeln!(s, "{ind}_delay_ms({value});");
                }
                Expr::Int { value } => {
                    let _ = writeln!(s, "{ind}avsv_delay_ms({value}U);");
                }
                e => {
                    let _ = writeln!(s, "{ind}avsv_delay_ms((uint16_t)({}));", self.expr(e));
                }
            },
            StmtKind::DelayUs { us } => {
                if self.opts.legacy_toolchain && *us > 10 {
                    let i = *counter;
                    *counter += 1;
                    let _ = writeln!(
                        s,
                        "{ind}for (uint16_t d{i} = 0; d{i} < {}U; d{i}++) {{\n{ind}    _delay_us(10);\n{ind}}}",
                        us / 10
                    );
                    if us % 10 != 0 {
                        let _ = writeln!(s, "{ind}_delay_us({});", us % 10);
                    }
                } else {
                    let _ = writeln!(s, "{ind}_delay_us({us});");
                }
            }
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let _ = writeln!(s, "{ind}if ({}) {{", self.expr(cond));
                self.block(s, then_body, depth + 1, counter);
                if !else_body.is_empty() {
                    let _ = writeln!(s, "{ind}}} else {{");
                    self.block(s, else_body, depth + 1, counter);
                }
                let _ = writeln!(s, "{ind}}}");
            }
            StmtKind::While { cond, body } => {
                let _ = writeln!(s, "{ind}while ({}) {{", self.expr(cond));
                self.block(s, body, depth + 1, counter);
                let _ = writeln!(s, "{ind}}}");
            }
            StmtKind::Repeat {
                count,
                index_var,
                body,
            } => {
                let i = *counter;
                *counter += 1;
                let _ = writeln!(
                    s,
                    "{ind}{{\n{ind}    const uint16_t n{i} = (uint16_t)({});\n{ind}    for (uint16_t i{i} = 0; i{i} < n{i}; i{i}++) {{",
                    self.expr(count)
                );
                if let Some(v) = index_var {
                    let t = self.var_type(v);
                    let _ = writeln!(s, "{ind}        v_{v} = ({})i{i};", t.c_type());
                }
                self.block(s, body, depth + 2, counter);
                let _ = writeln!(s, "{ind}    }}\n{ind}}}");
            }
            StmtKind::Call { function } => {
                let _ = writeln!(s, "{ind}fn_{function}();");
            }
            StmtKind::Return => {
                let _ = writeln!(s, "{ind}return;");
            }
            StmtKind::SetVar { name, value } => {
                let t = self.var_type(name);
                let e = self.expr(value);
                if t == VarType::Bool {
                    let _ = writeln!(s, "{ind}v_{name} = {e};");
                } else {
                    let _ = writeln!(s, "{ind}v_{name} = ({})({e});", t.c_type());
                }
            }
            StmtKind::UartSendString { text, newline } => {
                let mut t = c_string(text);
                if *newline {
                    t.push_str("\\r\\n");
                }
                let _ = writeln!(s, "{ind}avsv_uart_puts_P(PSTR(\"{t}\"));");
            }
            StmtKind::UartSendNumber { value, newline } => {
                let _ = writeln!(s, "{ind}avsv_uart_print_i32((int32_t)({}));", self.expr(value));
                if *newline {
                    let _ = writeln!(s, "{ind}avsv_uart_putc('\\r');\n{ind}avsv_uart_putc('\\n');");
                }
            }
            StmtKind::UartSendByte { value } => {
                let _ = writeln!(s, "{ind}avsv_uart_putc((uint8_t)({}));", self.expr(value));
            }
            StmtKind::UartReceiveByte { var } => {
                let t = self.var_type(var);
                if t == VarType::Bool {
                    let _ = writeln!(s, "{ind}v_{var} = (avsv_uart_getc() != 0U);");
                } else {
                    let _ = writeln!(s, "{ind}v_{var} = ({})avsv_uart_getc();", t.c_type());
                }
            }
        }
    }

    fn var_type(&self, name: &str) -> VarType {
        self.ir
            .variables
            .iter()
            .find(|v| v.name == name)
            .map(|v| v.var_type)
            .unwrap_or(VarType::Int16)
    }

    fn expr(&self, e: &Expr) -> String {
        match e {
            Expr::Int { value } => int_literal(*value),
            Expr::Bool { value } => (if *value { "true" } else { "false" }).into(),
            Expr::Var { name } => format!("v_{name}"),
            Expr::PinRead { pin } => format!("((IO_{}_PIN & (1U << IO_{}_BIT)) != 0U)", pin.label, pin.label),
            Expr::AdcRead { channel } => format!("((int16_t)avsv_adc_read({channel}U))"),
            Expr::AdcToMillivolts { raw, reference_mv } => {
                format!("((int32_t)({}) * {}L / 1024L)", self.expr(raw), reference_mv)
            }
            Expr::UartAvailable => "avsv_uart_available()".into(),
            Expr::Binary { op, a, b } => format!("({} {} {})", self.expr(a), op.c_op(), self.expr(b)),
            Expr::Not { a } => format!("(!{})", self.expr(a)),
        }
    }
}

/// FNV-1a 64-bit; used only to detect manual edits of generated files.
pub fn content_hash(data: &[u8]) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in data {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct WriteReport {
    pub written: Vec<String>,
    pub unchanged: Vec<String>,
    pub removed: Vec<String>,
}

/// Writes generated files into the project, refusing to overwrite files that
/// were modified by hand (unless `force`). A manifest of content hashes in
/// `src/generated/.avsv-generated.json` tracks what the generator wrote.
pub fn write_generated(root: &Path, code: &GeneratedCode, force: bool) -> CoreResult<WriteReport> {
    let dir = root.join(GENERATED_DIR);
    let manifest_path = dir.join(MANIFEST_NAME);
    let previous: BTreeMap<String, String> = std::fs::read_to_string(&manifest_path)
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();

    let mut conflicts = vec![];
    for f in &code.files {
        let path = root.join(&f.path);
        if let Ok(existing) = std::fs::read(&path) {
            let modified = match previous.get(&f.path) {
                Some(h) => *h != content_hash(&existing),
                None => !String::from_utf8_lossy(&existing).contains(GENERATED_MARKER),
            };
            if modified && existing != f.content.as_bytes() {
                conflicts.push(f.path.clone());
            }
        }
    }
    if !conflicts.is_empty() && !force {
        return Err(CoreError::Conflict(format!(
            "these generated files were edited by hand and would be overwritten: {}. Move your changes elsewhere or confirm regeneration.",
            conflicts.join(", ")
        )));
    }

    let mut report = WriteReport {
        written: vec![],
        unchanged: vec![],
        removed: vec![],
    };
    let mut manifest = BTreeMap::new();
    for f in &code.files {
        let path = root.join(&f.path);
        if std::fs::read(&path).ok().as_deref() == Some(f.content.as_bytes()) {
            report.unchanged.push(f.path.clone());
        } else {
            atomic_write(&path, f.content.as_bytes(), false)?;
            report.written.push(f.path.clone());
        }
        manifest.insert(f.path.clone(), content_hash(f.content.as_bytes()));
    }
    for (old, hash) in &previous {
        if manifest.contains_key(old) {
            continue;
        }
        let path = root.join(old);
        if std::fs::read(&path)
            .ok()
            .is_some_and(|c| content_hash(&c) == *hash)
        {
            std::fs::remove_file(&path).map_err(|e| CoreError::io(&path, e))?;
            report.removed.push(old.clone());
        }
    }
    let json =
        serde_json::to_string_pretty(&manifest).map_err(|e| CoreError::InvalidProject(e.to_string()))?;
    atomic_write(&manifest_path, json.as_bytes(), false)?;
    Ok(report)
}

